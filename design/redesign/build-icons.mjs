// Regenerates icons.js from the project's own icon set (lucide-react), so the draft uses the app's icons.
import { writeFileSync } from 'node:fs';
const names = ['lock','triangle-alert','arrow-left','arrow-right','rotate-cw','star','columns-2','puzzle','ellipsis-vertical','x','minus','square','search','plus','pin','pin-off','chevron-down','chevron-up','volume-2','volume-x','shield','download','key-round','settings','layers','file','file-archive','file-text','pause','play','folder','eye','eye-off','copy','check','refresh-cw','loader','panel-left','book-open','import','monitor'];
const out = {};
for (const n of names) {
  const { __iconData } = await import(`../../node_modules/lucide-react/dist/esm/icons/${n}.mjs`);
  out[n] = __iconData.node.map(([tag, { key, ...attrs }]) => [tag, attrs]); // eslint-disable-line no-unused-vars
}
writeFileSync(new URL('./icons.js', import.meta.url), `// lucide icons (ISC license), generated by build-icons.mjs from node_modules/lucide-react\nwindow.ICONS = ${JSON.stringify(out)};\n`);
console.log(Object.keys(out).length, 'icons');
